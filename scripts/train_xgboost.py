"""
SepsisSignal: Offline XGBoost Comparison Training Script.
Strictly follows project rules:
1. Does NOT overwrite models/model.joblib (saves to models/xgboost_model.joblib).
2. Reuses the exact patient splits from models/splits/*.txt.
3. Reuses the exact causal point-in-time features from src/features.py and medians from models/imputer.json.
4. Appends/updates offline XGBoost metrics in models/results/metrics.json.
"""

import argparse
import glob
import json
import os
import sys
from typing import Any, Dict, List, Tuple
import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import (
    average_precision_score,
    confusion_matrix,
    precision_recall_fscore_support,
)
import xgboost as xgb

# Ensure repository root is on sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src.features import extract_features_point_in_time


def parse_patient_psv(file_path: str) -> pd.DataFrame:
    """Read a single PhysioNet PSV file."""
    df = pd.read_csv(file_path, sep="|")
    if "Hour" not in df.columns:
        df["Hour"] = np.arange(1, len(df) + 1)
    return df


def load_split_ids(output_dir: str) -> Tuple[List[str], List[str], List[str]]:
    """Load the exact patient splits already generated by the baseline."""
    train_file = os.path.join(output_dir, "splits", "train_patients.txt")
    val_file = os.path.join(output_dir, "splits", "val_patients.txt")
    test_file = os.path.join(output_dir, "splits", "test_patients.txt")

    if not (os.path.exists(train_file) and os.path.exists(val_file) and os.path.exists(test_file)):
        raise FileNotFoundError(
            "Missing split files in models/splits/. Ensure baseline model has been trained first."
        )

    with open(train_file, "r", encoding="utf-8") as f:
        train_ids = [line.strip() for line in f if line.strip()]
    with open(val_file, "r", encoding="utf-8") as f:
        val_ids = [line.strip() for line in f if line.strip()]
    with open(test_file, "r", encoding="utf-8") as f:
        test_ids = [line.strip() for line in f if line.strip()]

    return train_ids, val_ids, test_ids


def load_training_imputer(output_dir: str) -> Dict[str, float]:
    """Load the exact baseline training-set medians."""
    imputer_file = os.path.join(output_dir, "imputer.json")
    if not os.path.exists(imputer_file):
        raise FileNotFoundError(
            "Missing models/imputer.json. Ensure baseline model has been trained first."
        )
    with open(imputer_file, "r", encoding="utf-8") as f:
        raw = json.load(f)
    return {k.lower(): float(v) for k, v in raw.items()}


def extract_cohort_dataset(
    patient_files: Dict[str, str],
    pids: List[str],
    imputer: Dict[str, float],
    cohort_name: str = "cohort",
) -> Tuple[np.ndarray, np.ndarray]:
    """Extract causal features and binary SepsisLabel for all hours of patients."""
    X_list = []
    y_list = []

    total = len(pids)
    print(f"[*] Extracting causal features for {cohort_name} ({total} patients)...")

    for i, pid in enumerate(pids):
        if (i + 1) % 5000 == 0 or (i + 1) == total:
            print(f"    Processed {i + 1}/{total} patients in {cohort_name}...")

        file_path = patient_files.get(pid)
        if not file_path or not os.path.exists(file_path):
            continue

        df = parse_patient_psv(file_path)
        label_col = "SepsisLabel" if "SepsisLabel" in df.columns else None

        raw_obs = []
        for _, row in df.iterrows():
            hr_val = int(row["Hour"])
            obs = {
                "patient_id": pid,
                "hour": hr_val,
                "hr": None if pd.isna(row.get("HR")) else float(row["HR"]),
                "sbp": None if pd.isna(row.get("SBP")) else float(row["SBP"]),
                "resp": None if pd.isna(row.get("Resp")) else float(row["Resp"]),
                "temp": None if pd.isna(row.get("Temp")) else float(row["Temp"]),
                "wbc": None if pd.isna(row.get("WBC")) else float(row["WBC"]),
            }
            raw_obs.append(obs)

        for _, row in df.iterrows():
            target_hour = int(row["Hour"])
            vec, _ = extract_features_point_in_time(
                raw_obs, target_hour=target_hour, imputer=imputer
            )
            X_list.append(vec.flatten())
            y_val = int(row[label_col]) if label_col and not pd.isna(row[label_col]) else 0
            y_list.append(y_val)

    return np.array(X_list, dtype=np.float32), np.array(y_list, dtype=np.int32)


def main():
    parser = argparse.ArgumentParser(description="Train SepsisSignal Offline XGBoost Comparison Model")
    parser.add_argument("--data_dir", type=str, required=True, help="Directory containing PhysioNet .psv files")
    parser.add_argument("--output_dir", type=str, default="models", help="Output directory for model artifacts")
    parser.add_argument("--max_train_patients", type=int, default=0, help="Optional limit on train patients (0 = all in split)")
    parser.add_argument("--max_val_patients", type=int, default=0, help="Optional limit on val patients (0 = all in split)")
    parser.add_argument("--max_test_patients", type=int, default=0, help="Optional limit on test patients (0 = all in split)")
    args = parser.parse_args()

    # 1. Discover all patient files
    print(f"[*] Scanning for patient PSV files in {args.data_dir}...")
    files = glob.glob(os.path.join(args.data_dir, "**", "*.psv"), recursive=True)
    if not files:
        print(f"[ERROR] No .psv files found in {args.data_dir}")
        sys.exit(1)

    patient_files = {}
    for f in files:
        pid = os.path.splitext(os.path.basename(f))[0]
        patient_files[pid] = f
    print(f"[*] Found {len(patient_files)} total patient PSV files.")

    # 2. Reuse the exact split patient IDs
    train_ids, val_ids, test_ids = load_split_ids(args.output_dir)
    print(f"[*] Loaded exact patient splits from {args.output_dir}/splits/:")
    print(f"    Train: {len(train_ids)} patients")
    print(f"    Val:   {len(val_ids)} patients")
    print(f"    Test:  {len(test_ids)} patients")

    if args.max_train_patients > 0:
        train_ids = train_ids[: args.max_train_patients]
        print(f"    [!] Subsampled train patients to: {len(train_ids)}")
    if args.max_val_patients > 0:
        val_ids = val_ids[: args.max_val_patients]
        print(f"    [!] Subsampled val patients to: {len(val_ids)}")
    if args.max_test_patients > 0:
        test_ids = test_ids[: args.max_test_patients]
        print(f"    [!] Subsampled test patients to: {len(test_ids)}")

    # 3. Load baseline training-set imputer values
    imputer = load_training_imputer(args.output_dir)
    print(f"[*] Reusing baseline training imputers: {imputer}")

    # 4. Extract causal point-in-time features
    X_train, y_train = extract_cohort_dataset(patient_files, train_ids, imputer, cohort_name="TRAIN")
    pos_rate = float(y_train.mean()) if len(y_train) > 0 else 0.0
    print(f"    TRAIN shape: {X_train.shape}, positive rate: {pos_rate:.4f}")

    X_val, y_val = extract_cohort_dataset(patient_files, val_ids, imputer, cohort_name="VALIDATION")
    print(f"    VALIDATION shape: {X_val.shape}")

    X_test, y_test = extract_cohort_dataset(patient_files, test_ids, imputer, cohort_name="TEST")
    print(f"    TEST shape: {X_test.shape}")

    # 5. Train XGBoost Model
    print("\n[*] Training XGBoost Classifier (tree_method='hist')...")
    num_pos = int(y_train.sum())
    num_neg = len(y_train) - num_pos
    scale_pos_weight = float(num_neg / max(1, num_pos))
    print(f"    scale_pos_weight: {scale_pos_weight:.2f}")

    xgb_model = xgb.XGBClassifier(
        n_estimators=150,
        max_depth=5,
        learning_rate=0.08,
        scale_pos_weight=scale_pos_weight,
        subsample=0.8,
        colsample_bytree=0.8,
        tree_method="hist",
        random_state=42,
        eval_metric="logloss",
        n_jobs=-1,
    )
    xgb_model.fit(X_train, y_train)

    # 6. Choose threshold on VALIDATION only
    print("\n[*] Selecting optimal alert threshold on VALIDATION split only...")
    val_probs = xgb_model.predict_proba(X_val)[:, 1]

    best_thresh = 0.25
    best_f1 = -1.0
    # Search thresholds targeting recall >= 0.70 while maximizing F1
    for t in np.linspace(0.05, 0.85, 81):
        preds = (val_probs >= t).astype(int)
        _, rec, f1, _ = precision_recall_fscore_support(y_val, preds, average="binary", zero_division=0)
        if rec >= 0.70 and f1 > best_f1:
            best_f1 = f1
            best_thresh = round(float(t), 4)

    # Fallback to pure max F1 if recall >= 0.70 not met
    if best_f1 < 0:
        for t in np.linspace(0.05, 0.85, 81):
            preds = (val_probs >= t).astype(int)
            _, rec, f1, _ = precision_recall_fscore_support(y_val, preds, average="binary", zero_division=0)
            if f1 > best_f1:
                best_f1 = f1
                best_thresh = round(float(t), 4)

    print(f"[*] Selected optimal threshold on validation: {best_thresh} (Validation F1: {best_f1:.4f})")

    # 7. Evaluate on HELD-OUT TEST patients
    print("\n[*] Evaluating on HELD-OUT TEST split...")
    test_probs = xgb_model.predict_proba(X_test)[:, 1]
    test_preds = (test_probs >= best_thresh).astype(int)

    auprc = float(average_precision_score(y_test, test_probs)) if y_test.sum() > 0 else 0.0
    prec, rec, f1, _ = precision_recall_fscore_support(y_test, test_preds, average="binary", zero_division=0)
    tn, fp, fn, tp = confusion_matrix(y_test, test_preds, labels=[0, 1]).ravel()
    spec = float(tn / (tn + fp)) if (tn + fp) > 0 else 0.0
    alert_rate = float(test_preds.mean() * 100)

    print("\n" + "=" * 50)
    print("XGBOOST HELD-OUT TEST SET EVALUATION METRICS:")
    print(f"  AUPRC:       {auprc:.4f}")
    print(f"  Precision:   {prec:.4f}")
    print(f"  Recall:      {rec:.4f}")
    print(f"  Specificity: {spec:.4f}")
    print(f"  Alert Rate:  {alert_rate:.2f} alerts per 100 patient-hours")
    print("=" * 50 + "\n")

    # 8. Save Artifacts
    # Rule 1: DO NOT OVERWRITE models/model.joblib!
    xgb_model_path = os.path.join(args.output_dir, "xgboost_model.joblib")
    joblib.dump(xgb_model, xgb_model_path)
    print(f"[OK] Saved XGBoost model to {xgb_model_path} (Live Logistic Regression untouched)")

    xgb_thresh_path = os.path.join(args.output_dir, "xgboost_threshold.json")
    with open(xgb_thresh_path, "w", encoding="utf-8") as f:
        json.dump({
            "threshold": best_thresh,
            "chosen_on": "validation",
            "selection_rule": "Targeted high recall (>=0.70) while maximizing F1 on validation set",
        }, f, indent=2)
    print(f"[OK] Saved XGBoost threshold to {xgb_thresh_path}")

    # Rule 4: Append / Update metrics in models/results/metrics.json
    metrics_path = os.path.join(args.output_dir, "results", "metrics.json")
    xgb_metrics_entry = {
        "name": "XGBoost (offline)",
        "auprc": round(auprc, 4),
        "precision": round(float(prec), 4),
        "recall": round(float(rec), 4),
        "specificity": round(float(spec), 4),
        "threshold": best_thresh,
        "alert_burden": f"{alert_rate:.1f} alerts per 100 patient-hours",
        "notes": "Offline comparison trained on identical splits and causal features with XGBoost hist tree method",
    }

    if os.path.exists(metrics_path):
        with open(metrics_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    else:
        data = {"models": [], "disclaimer": "Research prototype, not for clinical decision-making. Evaluated on PhysioNet 2019 test split."}

    updated = False
    for i, m in enumerate(data.get("models", [])):
        if "xgboost" in m.get("name", "").lower():
            data["models"][i] = xgb_metrics_entry
            updated = True
            break
    if not updated:
        data["models"].append(xgb_metrics_entry)

    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
    print(f"[OK] Updated XGBoost metrics in {metrics_path}")
    print("\n[SUCCESS] Offline XGBoost model training and evaluation complete!\n")


if __name__ == "__main__":
    main()
